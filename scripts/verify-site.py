def comparable_text(d):
    d=re.sub(r"Hawai[`‘’']i",'Hawaiʻi',d)
    for old,new in [('O‘ahu','Oʻahu'),('Kūali‘i','Kūaliʻi'),('‘Aha','ʻAha'),('Waiale‘e','Waialeʻe'),('University of Hawaii at Mānoa','University of Hawaiʻi at Mānoa')]:d=d.replace(old,new)
    d=re.sub(r'\b((?:[A-Z]{2,5} \d{3}[A-Z]?)(?:/[A-Z]{2,5} \d{3}[A-Z]?)?(?: \([A-Z]\))?) - ',r'\1: ',d)
    d=re.sub(r'(ES 320/SUST 321) (Hawaiʻi)',r'\1: \2',d)
    d=re.sub(r'(ES 455(?:/SUST 445)?): \(([BC])\)',r'\1 (\2):',d)
    for old,new in [('ES 318: Asian American: Survey','ES 318: Asian America'),('ES 318: Asian America: Survey','ES 318: Asian America'),('ES 370: Ethnic Literature of Hawaiʻi','ES 370: Literatures of Hawaiʻi'),('ES 370: Ethnic Literatures of Hawaiʻi','ES 370: Literatures of Hawaiʻi'),('Cultural & Labor Organizations','Cultural and labor organizations'),('Max of 3 credits towards certificate','maximum of 3 credits toward the certificate'),('May be substituted for ES 101','may be substituted for ES 101'),('Student Learning Outcomes (SLOs):','Student Learning Outcomes:')]:d=d.replace(old,new)
    d=re.sub(r'^\s*[-—]\s*','',d)
    return re.sub(r'\s+','',unicodedata.normalize('NFC',d))
