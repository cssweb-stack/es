class Scan(HTMLParser):
    def __init__(self,reviewed=False):super().__init__();self.reviewed=reviewed;self.ids=[];self.urls=[];self.h1=0;self.parts=[];self.skip=[];self.description=False
    def handle_starttag(self,t,attrs):
        a=dict(attrs)
        if t in ['script','style','svg']:self.skip.append(t)
        if t=='h1':self.h1+=1
        if a.get('id'):self.ids.append(a['id'])
        if t=='meta' and a.get('name')=='description' and a.get('content'):self.description=True
        if t in ['a','img','script','link','iframe']:
            v=a.get('href') if t in ['a','link'] else a.get('src')
            if v:self.urls.append(v)
    def handle_endtag(self,t):
        if self.skip and self.skip[-1]==t:self.skip.pop()
    def handle_data(self,d):
        if not self.skip and d.strip():
            value=comparable_text(d)
            if self.reviewed:
                for old,new in editorial_replacements.items():value=value.replace(old,new)
            self.parts.append(value)
